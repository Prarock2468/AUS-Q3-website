/**
 * Builds public/css/site-form.css: the Contact Us form design (git-hero / git-form / lead-card / buttons …) taken from
 * the Standard template's stylesheet, so forms look the same on pages with other templates (About, Services …),
 * which do not load main.min.css. Every rule is scoped to `.git-hero` on pages without the `t-main` class (the
 * templates that load main.min.css all have it), so nothing else changes and Standard pages keep their own styles.
 * Run after main.min.css changes: `node scripts/build-form-css.mjs`.
 */
import fs from 'fs'

const SOURCE = 'public/css/templates/main.min.css'
const TARGET = 'public/css/site-form.css'
const WANT = /\.git-|\.lead-card|\.lead-submit|\.lead-send|\.captcha|\.cap-q|\.lf\b|\.lf-row|\.form-errors|\.field-error|\.hp\b|\.lucide|\.btn\b|\.btn-|\.tick\b|\.form-done/
const SCOPE = '.git-hero'
/** Only on templates that do not load main.min.css (they all set html.t-main). */
const PAGE = 'html:not(.t-main)'
const scoped = (s) => (s.startsWith(SCOPE) ? `${PAGE} ${s}` : `${PAGE} ${SCOPE} ${s}`)

/** Splits CSS into top-level rules ("sel{…}" or "@media(…){…}"). */
function topLevel(css) {
  const out = []
  let depth = 0
  let start = 0
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) {
      out.push(css.slice(start, i + 1).trim())
      start = i + 1
    }
  }
  return out
}

/** Prefixes each selector in a list with the scope (unless it already starts inside it). */
const scopeSelectors = (list) =>
  list
    .split(/,(?![^(]*\))/)
    .map((s) => s.trim())
    .map(scoped)
    .join(',')

function scopeRule(rule) {
  if (rule.startsWith('@media') || rule.startsWith('@supports')) {
    const open = rule.indexOf('{')
    const inner = topLevel(rule.slice(open + 1, -1)).filter((r) => WANT.test(r.slice(0, r.indexOf('{'))))
    return inner.length ? `${rule.slice(0, open)}{${inner.map(scopeRule).join('')}}` : ''
  }
  if (rule.startsWith('@')) return '' // keyframes etc. come from the page's own stylesheets
  const open = rule.indexOf('{')
  const selectors = rule.slice(0, open)
  if (!WANT.test(selectors)) return ''
  return scopeSelectors(selectors) + rule.slice(open)
}

const css = fs.readFileSync(SOURCE, 'utf8')
const rules = topLevel(css).map(scopeRule).filter(Boolean)

/*
 * Buttons: common.min.css styles .btn only inside certain areas (":where(.t-main, .contact-band, …) .btn"), which
 * the form section on other templates is not part of. Take those rules and apply them inside the scope instead.
 */
const COMMON = 'public/css/common.min.css'
const buttonRules = topLevel(fs.readFileSync(COMMON, 'utf8'))
  .filter((r) => !r.startsWith('@'))
  .flatMap((r) => {
    const open = r.indexOf('{')
    const selectors = r
      .slice(0, open)
      .split(/,(?![^(]*\))/)
      .map((s) => s.trim())
      .filter((s) => /\.btn\b|\.btn-/.test(s))
      .map((s) => s.replace(/^:where\([^)]*\)\s*/, '').trim())
      .filter((s) => /^\.btn/.test(s))
    return selectors.length ? [`${[...new Set(selectors)].map(scoped).join(',')}${r.slice(open)}`] : []
  })

const header = `/* Generated by scripts/build-form-css.mjs from ${SOURCE} and ${COMMON} (buttons): the Contact Us form design, scoped to ${SCOPE}. Do not edit by hand. */\n`
fs.writeFileSync(TARGET, header + [...buttonRules, ...rules].join('\n') + '\n')
console.log(`buttons from ${COMMON}: ${buttonRules.length} rules`)
console.log(`${TARGET}: ${rules.length} rules, ${fs.statSync(TARGET).size} bytes`)
